#!/usr/bin/env python3
"""Generate pc_overlay_ids.h: one compile-time constant per overlay.

On the DS, FS_OVERLAY_ID(name) is the *address* of a linker-made symbol
whose value is the overlay's index in the overlay table, i.e. its position
among the `Overlay` sections of main.lsf. That is not a constant expression
in C and the symbol does not exist on PC, so the PC build uses an enum with
the same values.

Usage: python tools/pc_port/gen_overlay_ids.py OUT_HEADER
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def main():
    out = pathlib.Path(sys.argv[1])
    names = re.findall(r"^Overlay\s+(\w+)\s*$", (ROOT / "platinum.us" / "main.lsf.in").read_text(encoding="utf-8"), re.M)
    lines = ["/* Generated by tools/pc_port/gen_overlay_ids.py from platinum.us/main.lsf.in - do not edit. */",
             "#ifndef PC_OVERLAY_IDS_H", "#define PC_OVERLAY_IDS_H", "",
             "enum PcOverlayId {"]
    lines += [f"    PC_OVERLAY_ID_{n} = {i}," for i, n in enumerate(names)]
    lines += [f"    PC_OVERLAY_COUNT = {len(names)}", "};", "",
              "extern const char *const gPcOverlayNames[PC_OVERLAY_COUNT];", "", "#endif", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    src = out.with_suffix(".c")
    src.write_text("/* Generated by tools/pc_port/gen_overlay_ids.py - do not edit. */\n"
                   '#include "pc_overlay_ids.h"\n\n'
                   "const char *const gPcOverlayNames[PC_OVERLAY_COUNT] = {\n" +
                   "".join(f'    "{n}",\n' for n in names) + "};\n", encoding="utf-8", newline="\n")
    print(f"{len(names)} overlays -> {out}")


if __name__ == "__main__":
    main()
