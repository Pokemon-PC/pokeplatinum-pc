#!/usr/bin/env python3
"""Inventory every Nintendo DS / NitroSDK / NitroSystem dependency used by the
game code (src/ + include/), and write it to docs/PORTING_API_AUDIT.md.

Usage (from the repository root):
    python tools/pc_port/audit_nitro_api.py

Re-run it whenever the decompilation changes; the output is deterministic.
"""
import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCAN_DIRS = ["src", "include"]
OUT = ROOT / "docs" / "PORTING_API_AUDIT.md"

# (group title, PC HAL module that will own it, regex for the call/identifier)
GROUPS = [
    ("OS - kernel, threads, IRQ, ticks, heaps, reset", "os_pc.c", r"\bOS_[A-Za-z0-9_]+(?=\s*\()"),
    ("GX - 2D/3D display engine control, VRAM banks", "gfx_pc.c", r"\bGXS?_[A-Za-z0-9_]+(?=\s*\()"),
    ("G2/G2S - 2D BG/OBJ/window/blend registers", "gfx_pc.c", r"\bG2S?_[A-Za-z0-9_]+(?=\s*\()"),
    ("G3/G3X - 3D geometry engine", "gfx_pc.c (GL backend)", r"\bG3X?_[A-Za-z0-9_]+(?=\s*\()"),
    ("NNS_G2d - NitroSystem 2D (cells, OAM, fonts)", "lib/NitroSystem (recompiled)", r"\bNNS_G2d[A-Za-z0-9_]+(?=\s*\()"),
    ("NNS_G3d - NitroSystem 3D (models, animations)", "lib/NitroSystem (recompiled) + gfx_pc.c", r"\bNNS_G3d[A-Za-z0-9_]+(?=\s*\()"),
    ("NNS_Gfd - VRAM managers", "lib/NitroSystem (recompiled)", r"\bNNS_Gfd[A-Za-z0-9_]+(?=\s*\()"),
    ("NNS_Fnd - heaps / lists", "lib/NitroSystem (recompiled)", r"\bNNS_Fnd[A-Za-z0-9_]+(?=\s*\()"),
    ("NNS_Snd - sound archive player (SDAT)", "audio_pc.c", r"\bNNS_Snd[A-Za-z0-9_]+(?=\s*\()"),
    ("SND - low-level ARM7 sound", "audio_pc.c", r"\bSND_[A-Za-z0-9_]+(?=\s*\()"),
    ("FS - NitroFS files & overlays", "fs_pc.c", r"\bFS_[A-Za-z0-9_]+(?=\s*\()"),
    ("PAD - buttons", "input_pc.c", r"\bPAD_[A-Za-z0-9_]+(?=\s*\()"),
    ("TP - touch panel", "input_pc.c", r"\bTP_[A-Za-z0-9_]+(?=\s*\()"),
    ("CARD - cartridge ROM / backup (save)", "save_pc.c", r"\bCARD_[A-Za-z0-9_]+(?=\s*\()"),
    ("CTRDG - GBA slot (Pal Park / AGB detection)", "stub", r"\bCTRDG_[A-Za-z0-9_]+(?=\s*\()"),
    ("RTC - real-time clock", "os_pc.c", r"\bRTC_[A-Za-z0-9_]+(?=\s*\()"),
    ("PM - power management, LCD backlight", "os_pc.c", r"\bPM_[A-Za-z0-9_]+(?=\s*\()"),
    ("MI - memory copy/fill/DMA/compression", "mi_pc.c (portable C)", r"\bMI_[A-Za-z0-9_]+(?=\s*\()"),
    ("DC/IC - cache maintenance", "no-op", r"\b(?:DC|IC)_[A-Za-z0-9_]+(?=\s*\()"),
    ("CP - hardware divider / sqrt", "portable C", r"\bCP_[A-Za-z0-9_]+(?=\s*\()"),
    ("FX/MTX/VEC/MATH - fixed-point math", "lib/NitroSDK fx (recompiled)", r"\b(?:FX|MTX|VEC|MATH)_[A-Za-z0-9_]+(?=\s*\()"),
    ("WM/WVR/MB - wireless, download play", "stub (offline)", r"\b(?:WM|WVR|MB)_[A-Za-z0-9_]+(?=\s*\()"),
    ("DWC/SOC/WCM/CPS - Nintendo WFC online", "stub (offline)", r"\b(?:DWC|SOC|WCM|CPS)_[A-Za-z0-9_]+(?=\s*\()"),
    ("CRYPTO", "lib (recompiled)", r"\bCRYPTO_[A-Za-z0-9_]+(?=\s*\()"),
    ("SVC - BIOS calls", "portable C", r"\bSVC_[A-Za-z0-9_]+(?=\s*\()"),
    ("reg_* - direct I/O register access", "virtual register file (hw_pc.c)", r"\breg_[A-Z0-9_]+"),
    ("HW_* - fixed memory map (VRAM/OAM/palettes)", "virtual memory map (hw_pc.c)", r"\bHW_[A-Z0-9_]+"),
    ("Raw 0x04xxxxxx I/O addresses", "rewrite to reg_* macros", r"\(\s*vu?(?:8|16|32)\s*\*\s*\)\s*0x04[0-9A-Fa-f]{6}"),
]

EXTRA = [
    ("Inline ARM asm blocks (`asm void`, `asm {`)", r"\basm\s+(?:void|u32|s32|int|BOOL|static|\{)"),
    ("Metrowerks pragmas", r"#pragma\s+(?:force_active|opt_\w+|optimization_level|thumb|arm)"),
    ("Overlay loading (FS_*Overlay / HandleLoadOverlay)", r"\b(?:HandleLoadOverlay|FS_LoadOverlay|FS_UnloadOverlay|UnloadOverlayByID)\b"),
    ("Pointer stored in 32-bit integer (64-bit hazard)", r"\(\s*(?:u32|s32)\s*\)\s*(?:&|[A-Za-z_]\w*(?:->|\.)?\w*\b)(?=\s*[;,)+\-])"),
]


def iter_files():
    for d in SCAN_DIRS:
        for p in sorted((ROOT / d).rglob("*")):
            if p.suffix in (".c", ".h", ".cpp", ".inc") and p.is_file():
                yield p


def main():
    texts = {p: p.read_text(encoding="utf-8", errors="replace") for p in iter_files()}
    lines = [
        "# NitroSDK / hardware dependency audit",
        "",
        "Generated by `tools/pc_port/audit_nitro_api.py` - do not edit by hand.",
        f"Scanned: {', '.join(SCAN_DIRS)} ({len(texts)} files).",
        "",
        "| Group | PC owner | Unique symbols | Uses | Files |",
        "|---|---|---:|---:|---:|",
    ]
    details = []
    for title, owner, rx in GROUPS:
        r = re.compile(rx)
        sym_count = collections.Counter()
        sym_files = collections.defaultdict(set)
        for p, t in texts.items():
            for m in r.findall(t):
                m = re.sub(r"\s+", "", m)
                sym_count[m] += 1
                sym_files[m].add(p)
        files = set().union(*sym_files.values()) if sym_files else set()
        lines.append(f"| {title} | {owner} | {len(sym_count)} | {sum(sym_count.values())} | {len(files)} |")
        if sym_count:
            details.append(f"\n## {title}\n\nPC owner: `{owner}`\n")
            details.append("| Symbol | Uses | Files |\n|---|---:|---:|")
            for s, n in sorted(sym_count.items(), key=lambda kv: (-kv[1], kv[0])):
                details.append(f"| `{s}` | {n} | {len(sym_files[s])} |")
    lines.append("")
    lines.append("## Other portability hazards\n")
    lines.append("| Hazard | Uses | Files |\n|---|---:|---:|")
    for title, rx in EXTRA:
        r = re.compile(rx)
        n = 0
        f = 0
        for t in texts.values():
            k = len(r.findall(t))
            n += k
            f += 1 if k else 0
        lines.append(f"| {title} | {n} | {f} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines + details) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
