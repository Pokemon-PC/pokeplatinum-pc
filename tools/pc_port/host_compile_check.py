#!/usr/bin/env python3
"""Compile every game / library C file for the PC host (syntax only) and
summarise what breaks. Used to drive the PC port (milestone 3).

Usage (repository root):
    python tools/pc_port/host_compile_check.py [--cc gcc] [--jobs N] [paths...]

Writes docs/PORTING_COMPILE_STATUS.md and build-pc/compile_check/<file>.log.
Paths default to src/ and lib/*/src.
"""
import argparse
import collections
import concurrent.futures
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]

INCLUDES = [
    "src/platform_pc/nitro_compat", "build-pc/generated", "src", "include", "include/library", "files",
    "lib/include", "lib/NitroSDK/include", "lib/NitroSDK/include-mw", "lib/NitroSDK/include-pokediamond",
]
DEFINES = ["PLATFORM_PC=1", "HEARTGOLD", "GAME_REMASTER=0", "ENGLISH", "PM_KEEP_ASSERTS",
           "SDK_ARM9", "SDK_CODE_ARM", "SDK_FINALROM"]
FLAGS = ["-std=gnu11", "-fsyntax-only", "-fms-extensions", "-fsigned-char", "-fno-strict-aliasing",
         "-Wno-unknown-pragmas", "-Wno-multichar", "-Wno-pointer-to-int-cast", "-Wno-int-to-pointer-cast",
         "-include", "platform_pc_prefix.h", "-fmax-errors=20"]

ERR_RE = re.compile(r"^(?P<file>[^:]+):(?P<line>\d+):\d+: (?P<kind>error|warning): (?P<msg>.*)$")


def normalise(msg):
    msg = re.sub(r"'[^']*'", "'X'", msg)
    msg = re.sub(r"\b0x[0-9a-fA-F]+\b|\b\d+\b", "N", msg)
    return msg


def compile_one(cc, path):
    cmd = [cc] + FLAGS + [f"-I{i}" for i in INCLUDES] + [f"-D{d}" for d in DEFINES] + [str(path)]
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, errors="replace")
    return path, proc.returncode, proc.stderr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cc", default="gcc")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("paths", nargs="*")
    args = ap.parse_args()

    roots = args.paths or ["src", "lib/NitroSDK/src", "lib/NitroSystem/src", "lib/src", "lib/MSL_C/src",
                           "lib/NitroDWC/src", "lib/NitroWiFi/src", "lib/libCPS/src", "lib/libVCT/src",
                           "lib/dsprot/src", "lib/syscall/src"]
    files = []
    for r in roots:
        p = ROOT / r
        if p.is_file():
            files.append(p.relative_to(ROOT))
        elif p.is_dir():
            files += [f.relative_to(ROOT) for f in sorted(p.rglob("*.c"))
                      if "platform_pc" not in f.parts]

    logdir = ROOT / "build-pc" / "compile_check"
    logdir.mkdir(parents=True, exist_ok=True)

    failed = {}
    first_errors = collections.Counter()
    all_errors = collections.Counter()
    err_locations = collections.Counter()
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as ex:
        for path, rc, err in ex.map(lambda f: compile_one(args.cc, f), files):
            (logdir / (str(path).replace("/", "__").replace("\\", "__") + ".log")).write_text(err, encoding="utf-8")
            if rc == 0:
                continue
            errs = [m for m in (ERR_RE.match(l) for l in err.splitlines()) if m and m["kind"] == "error"]
            failed[str(path)] = errs
            if errs:
                first_errors[normalise(errs[0]["msg"])] += 1
            for m in errs:
                all_errors[normalise(m["msg"])] += 1
                loc = m["file"].replace("\\", "/")
                if loc.startswith(str(ROOT).replace("\\", "/")):
                    loc = loc[len(str(ROOT)) + 1:]
                err_locations[loc] += 1

    by_root = collections.Counter()
    by_root_fail = collections.Counter()
    for f in files:
        key = "/".join(pathlib.PurePath(f).parts[:2] if str(f).startswith("lib") else pathlib.PurePath(f).parts[:1])
        by_root[key] += 1
        if str(f) in failed:
            by_root_fail[key] += 1

    out = ["# Host compile status", "", "Generated by `tools/pc_port/host_compile_check.py`.", "",
           f"**{len(files) - len(failed)} / {len(files)} files compile** for the PC host.", "",
           "| Tree | Files | Failing |", "|---|---:|---:|"]
    for k in sorted(by_root):
        out.append(f"| `{k}` | {by_root[k]} | {by_root_fail[k]} |")
    out += ["", "## Most common first errors", "", "| Files | Error |", "|---:|---|"]
    for msg, n in first_errors.most_common(40):
        out.append(f"| {n} | `{msg[:150]}` |")
    out += ["", "## Files where errors are reported (headers first)", "", "| Errors | Location |", "|---:|---|"]
    for loc, n in err_locations.most_common(40):
        out.append(f"| {n} | `{loc}` |")
    out += ["", "## Failing files", ""]
    for f in sorted(failed):
        first = failed[f][0]["msg"][:120] if failed[f] else "(no error line)"
        out.append(f"- `{f}` — {first}")
    (ROOT / "docs" / "PORTING_COMPILE_STATUS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(files) - len(failed)}/{len(files)} compile; report: docs/PORTING_COMPILE_STATUS.md")
    for k in sorted(by_root):
        print(f"  {k:28} {by_root[k] - by_root_fail[k]:5}/{by_root[k]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
