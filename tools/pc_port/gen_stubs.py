#!/usr/bin/env python3
"""Generates C stubs for library functions the PC build does not provide
(online services: NitroDWC/NitroWiFi/libvct/ppwlobby; GBA slot, microphone,
local wireless parts...).

Each stub keeps the original declaration in a comment, logs its first call
(pc_stub_called) and returns a neutral value. Only the return type matters to
callers (stubs use `RET name()`, unspecified arguments): pointer, 64-bit
integer, void or int. Values that must keep the game moving are in OVERRIDES.

    python tools/pc_port/gen_stubs.py OUT_DIR SYMBOL_LIST

SYMBOL_LIST: one name per line (the linker's undefined symbols).
"""
import argparse
import collections
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SEARCH = ["include", "lib", "src", "subprojects/NitroSDK-4.2.30001/include", "subprojects/NitroSystem-071126.1/include",
          "subprojects/NitroDWC-2.2.30008/include", "subprojects/NitroWiFi-2.1.30003/include",
          "subprojects/libvct-1.3.1/include"]

# Return expressions that differ from "zero" because callers wait on them.
OVERRIDES = {}

SIXTY_FOUR = {"u64", "s64", "OSTick", "long long", "unsigned long long", "fx64", "OSTime"}


def index_headers():
    files = []
    for d in SEARCH:
        for dp, _, fs in os.walk(os.path.join(ROOT, d)):
            for f in fs:
                if f.endswith((".h", ".hpp")):
                    files.append(os.path.join(dp, f))
    return files


def find_decl(name, texts):
    pat = re.compile(r"(^|[;}\n])\s*((?:extern\s+)?[A-Za-z_][\w\s\*]*?[\s\*])%s\s*\(([^;{]*?)\)\s*;" % re.escape(name),
                     re.S)
    for path, text in texts:
        m = pat.search(text)
        if m:
            ret = " ".join(m.group(2).replace("extern", "").split())
            return path, ret, " ".join(("%s%s(%s)" % (m.group(2), name, m.group(3))).split())
    return None


def generic_return(ret):
    r = ret.replace("const ", "").replace("static ", "").replace("inline ", "").strip()
    if "*" in r:
        return "void *", "NULL"
    if r == "void":
        return "void", None
    if r in SIXTY_FOUR:
        return "long long", "0"
    if r in ("float", "f32"):
        return "float", "0.0f"
    return "int", "0"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("symbols")
    a = ap.parse_args()
    names = [l.strip() for l in open(a.symbols, encoding="utf-8") if l.strip()]
    texts = [(p, open(p, encoding="utf-8", errors="replace").read()) for p in index_headers()]
    by_origin = collections.defaultdict(list)
    missing = []
    for n in names:
        d = find_decl(n, texts)
        if d is None:
            missing.append(n)
            continue
        by_origin[d[0]].append((n, d[2], d[1]))
    os.makedirs(a.out_dir, exist_ok=True)
    for path, entries in by_origin.items():
        rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
        stem = re.sub(r"\W+", "_", rel)
        lines = ["/* Generated by tools/pc_port/gen_stubs.py - offline stubs for functions declared in %s." % rel,
                 " * The original declaration is kept in a comment above each stub. */",
                 "#include <stddef.h>", "", "void pc_stub_called(const char *name);", ""]
        for n, text, ret in sorted(entries):
            rtype, rval = generic_return(ret)
            rval = OVERRIDES.get(n, rval)
            body = ['    pc_stub_called("%s");' % n]
            if rtype != "void":
                body.append("    return %s;" % rval)
            lines.append("/* %s; */\n%s %s() {\n%s\n}\n" % (text.replace("*/", "* /"), rtype, n, "\n".join(body)))
        with open(os.path.join(a.out_dir, "stub_%s.c" % stem), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
    print("%d stubs in %d files; %d without a declaration" % (len(names) - len(missing), len(by_origin), len(missing)))
    if missing:
        print("  no declaration:", " ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
