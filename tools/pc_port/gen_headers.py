    ap.add_argument("out")
    ap.add_argument("--rom-dir")
    ap.add_argument("--hosttools", help="folder with speciesproc, itemproc... (tools/dataproc)")
    ap.add_argument("--enums-only", action="store_true", help="metang enumerations only (needed by the tools)")
    ap.add_argument("--stamp")
    ap.add_argument("--strict", action="store_true")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
