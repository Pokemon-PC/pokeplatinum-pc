# ------------------------------------------------------------------ text banks
def msgenc_header(rel_path, ids):
    guard = "".join("_" if c in "/.-" else c.upper() for c in rel_path)
    lines = ["/***************************************************",
             " * WARNING: This file was autogenerated by msgenc. *",
             " *               DO NOT MODIFY                     *",
             " ***************************************************/", "",
             "#ifndef MSGENC_" + guard, "#define MSGENC_" + guard, ""]
    for i, ident in enumerate(ids):
        lines.append("#define %s %d" % (ident, i))
    lines.append("#define %s_ENTRY_COUNT %d" % (guard[4:-2], len(ids)))
    lines += ["", "#endif // MSGENC_" + guard, ""]
    return "\n".join(lines)


def text_bank_ids(path):
    with open(path, encoding="utf-8") as f:
        doc = json.load(f)
    return [m.get("id", "BAD_SYMBOL") for m in doc["messages"]]


def gen_text_banks(out, extra_dirs=()):
    banks = [l.strip() for l in open(os.path.join(ROOT, "generated", "text_banks.txt"), encoding="utf-8")
             if l.strip()]
    done, missing = 0, []
    for const in banks:
        name = const.replace("TEXT_BANK_", "").lower()
        src = None
        for d in [os.path.join(ROOT, "res", "text")] + list(extra_dirs):
            p = os.path.join(d, name + ".json")
            if os.path.exists(p):
                src = p
                break
        if src is None:
            missing.append(name)
            continue
        rel = "res/text/bank/%s.h" % name
        write_if_changed(os.path.join(out, rel), msgenc_header(rel, text_bank_ids(src)))
        done += 1
    return done, missing


# ------------------------------------------------------------------ NARC indices
def guardify(s):
    return "".join(c if (c.isalnum() and c.isascii()) or c == "_" else "_" for c in s)


def naix_text(rel_narc, members):
    base = rel_narc[:rel_narc.rindex(".")]
    guard = guardify(base + ".naix")
    lines = ["/*", " * This file was generated by nitroarc for '%s'" % rel_narc,
             " * DO NOT MODIFY IT; MANUAL EDITS WILL BE LOST", " */", "",
             "#ifndef " + guard, "#define " + guard, ""]
    seen = {}
    for i, m in enumerate(members):
        hits = seen.get(m, 0)
        seen[m] = hits + 1
        name = guardify(m) + ("_%d" % hits if hits else "")
        lines.append("#define %s %d" % (name, i))
    lines += ["", "#define %s_COUNT %d" % (guard[:-5], len(members)), "", "#endif /* %s */" % guard, ""]
    return "\n".join(lines)


def recs_text(members):
    """The .recs file nitroarc writes next to an index (read by tools/dataproc):
    a metadata record, then one record per member: file name, symbol."""
    rs, us = "", ""
    seen, recs = {}, ["private" + rs]
    for m in members:
        hits = seen.get(m, 0)
        seen[m] = hits + 1
        recs.append(m + us + guardify(m) + ("_%d" % hits if hits else "") + rs)
    return "".join(recs)


def read_order(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out


def iter_custom_targets(text):
    """Yields (name, body, variable) for each custom_target(...) call
    (balanced parens); variable is what the target is assigned to, if any."""
    for m in re.finditer(r"(?:(\w+)\s*=\s*)?custom_target\(\s*(?:'([^']+)'|(\w+))", text):
        start = text.index("custom_target", m.start())
        depth, i = 0, start + len("custom_target")
        while i < len(text):
            c = text[i]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            elif c == "#":
                while i < len(text) and text[i] != "\n":
                    i += 1
            i += 1
        yield m.group(2) or m.group(3), text[start:i + 1], m.group(1)


