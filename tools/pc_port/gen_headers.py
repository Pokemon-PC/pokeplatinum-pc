#!/usr/bin/env python3
"""Generates the C headers that the Platinum code includes, without the DS
toolchain (Metrowerks) or Meson.

The DS build (meson) produces these headers while it builds the ROM data. On
PC the data comes from the player's ROM, so only the headers are needed:

  generated/<name>.h, .py     metang enumerations (generated/meson.build)
  res/text/bank/<bank>.h      text bank message IDs (msgenc -H format)
  <res dir>/<narc>.naix       NARC member indices (nitroarc --index format)

    python tools/pc_port/gen_headers.py OUT_DIR [--rom-dir pc_data/fr]

With --rom-dir, every NARC index is checked against the member count of the
same archive in the player's ROM (platinum.us/filesys.csv gives the path).
"""
import argparse
