def map_entries():
    """MAP_HEADER_* members of include/constants/fieldmap.h, in order."""
    src = open(os.path.join(ROOT, "include", "constants", "fieldmap.h"), encoding="utf-8").read()
    body = src[src.index("enum MapHeaderID"):]
    body = body[body.index("{") + 1:body.index("}")]
    body = re.sub(r"//[^\n]*", "", body)
    names = [m.split("=")[0].strip() for m in body.split(",") if m.strip()]
    return [n for n in names if n not in ("MAP_HEADER_INVALID", "MAP_HEADER_DYNAMIC")]


