def gen_naix(out, rom_dir=None, special=None):
    special = special or {}
    rom_map = {}
    csv = os.path.join(ROOT, "platinum.us", "filesys.csv")
    for line in open(csv, encoding="utf-8").read().splitlines()[1:]:
        if "," in line:
            s, t = line.split(",", 1)
            rom_map[s.strip()] = t.strip().lstrip("/")
    made, skipped, bad = [], [], []
    for dirpath, _, files in os.walk(os.path.join(ROOT, "res")):
        if "meson.build" not in files:
            continue
        rel_dir = os.path.relpath(dirpath, ROOT).replace("\\", "/")
        text = open(os.path.join(dirpath, "meson.build"), encoding="utf-8").read()
        for tname, body, var in iter_custom_targets(text):
            outs = re.search(r"output\s*:\s*\[([^\]]*)\]", body)
            if not outs:
                continue
            outs = re.findall(r"'([^']+)'", outs.group(1))
            naix = [o for o in outs if o.endswith(".naix")]
            narc = [o for o in outs if o.endswith(".narc")]
            if not naix:
                continue
            rel_narc = "%s/%s" % (rel_dir, narc[0] if narc else naix[0].replace(".naix", ".narc"))
            m = re.search(r"'--(?:files-from|order-file)'\s*,\s*files\('([^']+)'\)", body)
            members = None
            if rel_narc in special:
                members = special[rel_narc]
            elif m:
                members = read_order(os.path.join(dirpath, m.group(1)))
            else:
                v = re.search(r"'--files-from'\s*,\s*(\w+)", body)
                key = v.group(1) if v else None
                single = re.search(r"'--single-file'\s*,\s*'([^']+)'", body)
                if single:
                    members = [single.group(1)]
                elif (rel_dir, key) in special:
                    members = special[(rel_dir, key)]
                elif rel_narc in special:
                    members = special[rel_narc]
            if members is None:
                skipped.append("%s/%s" % (rel_dir, naix[0]))
                continue
            write_if_changed(os.path.join(out, rel_dir, naix[0]), naix_text(rel_narc, members))
            write_if_changed(os.path.join(out, rel_dir, naix[0][:-5] + ".recs"), recs_text(members))
            if var:
                NARC_RECS[var] = os.path.join(out, rel_dir, naix[0][:-5] + ".recs")
            made.append(rel_narc)
            if rom_dir and rel_narc in rom_map:
                count = narc_count(rom_file(rom_dir, rom_map[rel_narc]))
                if count is not None and count != len(members):
                    bad.append("%s: %d members in the index, %d in the ROM" % (rel_narc, len(members), count))
    return made, skipped, bad


NARC_RECS = {}   # meson variable of a NARC target -> its .recs file


def png_rows_4bpp(path):
    """Rows of a 4-bit indexed PNG as packed bytes (left pixel in the high
    nibble), the way nitrogfx reads them."""
    import zlib
    data = open(path, "rb").read()
    pos, idat, w = 8, b"", None
    while pos < len(data):
        n = int.from_bytes(data[pos:pos + 4], "big")
        kind = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = body[0:4], body[4:8], body[8], body[9], body[10], body[11], body[12]
            w, h = int.from_bytes(w, "big"), int.from_bytes(h, "big")
            if depth != 4 or ctype != 3 or interlace:
                raise RuntimeError("%s: only 4-bit indexed PNGs are supported" % path)
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw = zlib.decompress(idat)
    stride = (w + 1) // 2
    rows, prev = [], bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - 1] if x > 0 else 0
            b = prev[x]
            c = prev[x - 1] if x > 0 else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line))
        prev = line
    return w, h, rows


def gen_embeds(out):
    """Images embedded in the program as C arrays (nitrogfx IMAGE.png OUT.4bpp
    -embed NAME): 8x8 tiles, left to right then top to bottom."""
    n = 0
    for dirpath, _, files in os.walk(os.path.join(ROOT, "res")):
        if "meson.build" not in files:
            continue
        text = open(os.path.join(dirpath, "meson.build"), encoding="utf-8").read()
        for tname, body, var in iter_custom_targets(text):
            m = re.search(r"'-embed'\s*,\s*'(\w+)'", body)
            if not m:
                continue
            png = re.search(r"files\('([^']+\.png)'\)", body).group(1)
            w, h, rows = png_rows_4bpp(os.path.join(dirpath, png))
            buf = bytearray()
            for ty in range(h // 8):
                for tx in range(w // 8):
                    for j in range(8):
                        for k in range(4):
                            pair = rows[ty * 8 + j][tx * 4 + k]
                            buf.append(((pair & 15) << 4) | (pair >> 4))
            name = m.group(1)
            lines = ["#ifndef GUARD_EMBEDDABLE_%s_H" % name, "#define GUARD_EMBEDDABLE_%s_H" % name, "",
                     "__attribute__((aligned(4))) const u8 %s[] = {" % name]
            lines += ["    0x%02X," % b for b in buf]
            lines += ["};", "", "#endif // GUARD_EMBEDDABLE_%s_H" % name, ""]
            rel_dir = os.path.relpath(dirpath, ROOT)
            write_if_changed(os.path.join(out, rel_dir, png[:-4] + ".4bpp.h"), "\n".join(lines))
            n += 1
    return n


def gen_resdat(out, hosttools):
    """Sprite-template headers (res/graphics/sprite_templates/*.h) made by
    tools/dataproc's resdatproc from the .recs of the NARCs they use."""
    exe = ".exe" if os.name == "nt" else ""
    d = os.path.join(ROOT, "res", "graphics", "sprite_templates")
    text = open(os.path.join(d, "meson.build"), encoding="utf-8").read()
    odir = os.path.join(out, "res", "graphics", "sprite_templates")
    os.makedirs(odir, exist_ok=True)
    n = 0
    for tname, body, var in iter_custom_targets(text):
        if "resdatproc_exe" not in body:
            continue
        inputs = re.findall(r"(\w+)\[2\]", body[body.index("input"):body.index("command")])
        cmd = [os.path.join(hosttools, "resdatproc" + exe)]
        for define in re.findall(r"'-D'\s*,\s*'([^']+)'", body):
            name, ref = define.split(":", 1)
            idx = int(re.match(r"@INPUT(\d+)@", ref).group(1))
            # Looked up under REPO_BUILD (the generated root) by the tool.
            recs = os.path.relpath(NARC_RECS[inputs[idx]], out).replace(os.sep, "/")
            cmd += ["-D", "%s:%s" % (name, recs)]
        cmd += ["-p", re.search(r"'-p'\s*,\s*'([^']+)'", body).group(1), "-o", odir,
                os.path.join(d, re.search(r"files\('([^']+\.json)'\)", body).group(1))]
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            raise RuntimeError("resdatproc failed for %s:\n%s%s" % (tname, r.stdout, r.stderr))
        n += 1
    return n


_rom_basenames = {}


def rom_file(rom_dir, path):
    """Path of a ROM file; localized ROMs move some archives under
    resource/<lang>/ (same file name), as the game's own path table does."""
    p = os.path.join(rom_dir, path)
    if os.path.exists(p):
        return p
    if rom_dir not in _rom_basenames:
        names = {}
        res = os.path.join(rom_dir, "resource")
        for d, _, fs in os.walk(res):
            for f in fs:
                names.setdefault(f, os.path.join(d, f))
        _rom_basenames[rom_dir] = names
    return _rom_basenames[rom_dir].get(os.path.basename(path), p)


def narc_count(path):
    try:
        with open(path, "rb") as f:
            data = f.read(0x40)
    except OSError:
        return None
    if data[:4] != b"NARC":
        return None
    hdr = int.from_bytes(data[12:14], "little")
    if data[hdr:hdr + 4] != b"BTAF":
        return None
    return int.from_bytes(data[hdr + 8:hdr + 10], "little")


