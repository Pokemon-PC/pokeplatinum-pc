import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    try:
        with open(path, "r", encoding="utf-8", newline="") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


# --------------------------------------------------------------- metang enums
def run_metang(args, cwd):
    """Runs subprojects/metang/metang.py in this process (one Python start-up
    per enumeration made the generation take minutes on Windows)."""
    mdir = os.path.join(ROOT, "subprojects", "metang")
    if mdir not in sys.path:
        sys.path.insert(0, mdir)
    script = os.path.join(mdir, "metang.py")
    code = compile(open(script, encoding="utf-8").read(), script, "exec")
    old_argv, old_cwd = sys.argv, os.getcwd()
    sys.argv = ["metang.py"] + args
    os.chdir(cwd)
    env = {"__name__": "__main__", "__file__": script}
    try:
        exec(code, env)
    except SystemExit as e:
        if e.code not in (None, 0):
            raise RuntimeError("metang failed: %r" % args)
    finally:
        # metang leaves its output open (it expects the process to exit).
        for name in ("fout", "fin"):
            f = env.get(name)
            if f is not None and f not in (sys.stdout, sys.stdin):
                f.close()
        sys.argv = old_argv
        os.chdir(old_cwd)


def gen_metang(out):
    src = open(os.path.join(ROOT, "generated", "meson.build"), encoding="utf-8").read()
    gens = re.findall(r"'(\w+)'\s*:\s*\{([^}]*)\}", src)
    metang = os.path.join(ROOT, "subprojects", "metang", "metang.py")
    n = 0
    for key, body in gens:
        kind = re.search(r"'type'\s*:\s*'(\w+)'", body)
        tag = re.search(r"'tag'\s*:\s*'(\w+)'", body)
        if not kind or not tag:
            continue
        extra = re.findall(r"'(--[\w-]+)'", re.search(r"'extra'\s*:\s*\[([^\]]*)\]", body).group(1)) \
            if "'extra'" in body else []
        txt = os.path.join(ROOT, "generated", key + ".txt")
        for lang, ext in (("c", ".h"), ("py", ".py")):
            dst = os.path.join(out, "generated", key + ext)
            if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(txt):
                continue
            rel_dst = "generated/" + key + ext
            cmd = [sys.executable, metang, kind.group(1), "--tag-name", tag.group(1), "--output", rel_dst]
            if lang == "c":
                cmd += ["--guard", "POKEPLATINUM_GENERATED"]
            else:
                cmd += ["--lang", "py"]
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            # metang names its guard after the output path: run from OUT so it
            # reads generated/<key>.h, as in the DS build directory.
            run_metang(cmd[2:] + extra + [txt], out)
            n += 1
    open(os.path.join(out, "generated", "__init__.py"), "a").close()
    return len(gens), n


def gen_fx_const(out):
    """nitro/fx/fx_const.h (NitroSDK gen/nitro/fx/gen_fx_const.py)."""
